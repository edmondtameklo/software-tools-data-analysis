print("Отрасль #2 потребляет: 24, 36, 23  | Конечный продукт: 217 | Валовой выпуск: 300")
print("Отрасль #3 потребляет: 11, 27, 26  | Конечный продукт: 135 | Валовой выпуск: 200")
print("\nУсловие: конечный продукт отрасли #2 увеличивается в 3 раза")
print("         отрасли #1 и #3 сохраняются на прежнем уровне")

# Данные из таблицы варианта 6
X = np.array([200, 300, 200])  # Валовой выпуск
Y = np.array([154, 217, 135])  # Конечный продукт

# Матрица межотраслевых поставок
x_table = np.array([
    [13, 15, 18],
    [24, 36, 23],
    [11, 27, 26]
])

print(f"\n1. Валовой выпуск X: {X}")
print(f"2. Конечный продукт Y: {Y}")
print(f"3. Матрица межотраслевых поставок:")
print(f"{x_table}")

# Вычисление матрицы прямых затрат A
print(f"\n4. Матрица прямых затрат A (a_ij = x_ij / X_j):")
A = x_table / X
print(f"{A}")
print(f"{np.round(A, 4)}")

# Проверка продуктивности
print(f"\n5. Проверка продуктивности матрицы A:")
col_sums = np.sum(A, axis=0)
print(f"   Суммы по столбцам: {np.round(col_sums, 4)}")
max_sum = np.max(col_sums)
print(f"   Максимальная сумма: {max_sum:.4f}")
if max_sum < 1:
    print(f"   ✓ Матрица ПРОДУКТИВНА ({max_sum:.4f} < 1)")
else:
    print(f"   ✗ Матрица НЕПРОДУКТИВНА ({max_sum:.4f} >= 1)")

# Матрица полных затрат S = (E - A)^(-1)
print(f"\n6. Матрица полных затрат S = (E - A)^(-1):")
E = np.eye(3)
S = np.linalg.inv(E - A)
print(f"{np.round(S, 6)}")

# Проверка: S должно быть близко к E + A + A^2 + ...
print(f"\n7. Проверка S ≈ E + A + A^2:")
S_approx = E + A + A @ A
print(f"   S (точное):")
print(f"   {np.round(S, 6)}")
print(f"   E + A + A^2:")
print(f"   {np.round(S_approx, 6)}")

# Новый вектор конечного продукта
print(f"\n8. Новый вектор конечного продукта Y_нов:")
Y_new = Y.copy()
Y_new[1] = Y[1] * 3  # Отрасль #2 увеличивается в 3 раза
print(f"   Y_исх = {Y}")
print(f"   Y_нов = {Y_new}")
print(f"   (отрасль #2: {Y[1]} × 3 = {Y_new[1]})")

# Новый вектор валового выпуска
print(f"\n9. Новый вектор валового выпуска X_нов = S × Y_нов:")
X_new = S @ Y_new
print(f"   X_нов = {np.round(X_new, 4)}")

# Сравнение
print(f"\n10. Сравнение старого и нового валового выпуска:")
print(f"    Отрасль | Старый X | Новый X  | Изменение | Изменение %")
print(f"    " + "-" * 60)
for i in range(3):
    change = X_new[i] - X[i]
    change_pct = (change / X[i]) * 100
    print(f"    #{i+1}      | {X[i]:8.2f} | {X_new[i]:8.2f} | {change:9.2f} | {change_pct:6.2f}%")

