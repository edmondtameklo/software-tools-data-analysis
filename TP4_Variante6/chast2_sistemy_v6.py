# Система #1 (Вариант 6)
print("\n--- Система #1 ---")
print("3x1 - 2x2 + 3x3 - x4 = 0")
print("4x1 + 10x2 - 4x3 + x4 = 15")
print("2x1 - 14x2 + 2x3 + 2x4 = 8")
print("3x1 + x2 - x3 + 3x4 = 16")

A1 = np.array([
    [3, -2, 3, -1],
    [4, 10, -4, 1],
    [2, -14, 2, 2],
    [3, 1, -1, 3]
], dtype=float)

b1 = np.array([0, 15, 8, 16], dtype=float)

# Решение
try:
    x1 = np.linalg.solve(A1, b1)
    print(f"\nРешение системы #1:")
    for i, val in enumerate(x1, 1):
        print(f"  x{i} = {val:.4f}")
    
    # Проверка
    check = A1 @ x1
    print(f"\nПроверка A @ x = b:")
    print(f"  {check}")
    print(f"  Исходный вектор b: {b1}")
    print(f"  Точность: {np.max(np.abs(check - b1)):.10f}")
except np.linalg.LinAlgError:
    print("Система #1 вырождена, нет единственного решения!")

# Система #2 (Вариант 6)
