from functools import reduce

def find_max(lst):
    """
    Возвращает максимальный элемент списка.
    Использует reduce() и лямбда-функцию.
    
    Параметры:
        lst (list): Список чисел
        
    Возвращает:
        число или None: Максимальный элемент списка
    """
    if not lst:
        return None
    
    maksimum = reduce(lambda a, b: a if a > b else b, lst)
    return maksimum

